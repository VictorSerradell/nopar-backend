-- V14: registro de auditoria de las acciones sobre cuentas (alta, desactivacion, reactivacion, cambios de contrasena y
-- ascenso a super administrador): quien lo hizo, sobre quien y cuando.
--
-- No hay claves foraneas a users a proposito: el registro guarda el NOMBRE de quien actuo y de sobre quien, de modo que
-- sigue siendo legible aunque esa cuenta se renombre o se borre. "sistema" es el actor de lo que ocurre sin un usuario
-- (el arranque de la aplicacion, por ejemplo).

create table audit_events (
    id bigint generated by default as identity primary key,
    created_at timestamp(6) not null,
    action varchar(30) not null,
    actor_username varchar(255) not null,
    target_user_id bigint,
    target_username varchar(255),
    detail varchar(500),
    constraint audit_events_action_check check (action in
        ('USER_CREATED', 'USER_DEACTIVATED', 'USER_ACTIVATED', 'PASSWORD_CHANGED', 'PASSWORD_RESET', 'SUPER_ADMIN_GRANTED'))
);

-- El listado va del mas reciente al mas antiguo
create index idx_audit_events_created_at on audit_events (created_at desc, id desc);
