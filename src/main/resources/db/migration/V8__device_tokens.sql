-- V8: dispositivos registrados para las notificaciones push. Cada fila es la instalacion de una app (Android, iOS
-- o web) de un usuario, identificada por su token de Firebase Cloud Messaging.

create table device_tokens (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    token varchar(512) not null,
    platform varchar(20) not null,
    created_at timestamp(6) not null,
    last_seen_at timestamp(6) not null,
    -- Un token es una sola instalacion: si otro usuario inicia sesion en ese dispositivo, el token cambia de usuario.
    -- La restriccion tambien sirve de indice para registrar y para borrar por token
    constraint uk_device_tokens_token unique (token),
    -- Al borrar un usuario se borran sus dispositivos
    constraint fk_device_tokens_user foreign key (user_id) references users (id) on delete cascade,
    constraint device_tokens_platform_check check (platform in ('ANDROID', 'IOS', 'WEB'))
);

-- PostgreSQL no indexa por si solo las claves foraneas: los dispositivos de un usuario se cuentan al registrar y se
-- buscan al enviarle un aviso
create index idx_device_tokens_user on device_tokens (user_id);
