-- V11: chat de cada ola. Hay un chat por ola y dia: lo leen y lo escriben los conductores con turno en esa ola ese
-- dia, los encargados y los administradores. Cada mensaje lleva texto, una foto o las dos cosas.

create table wave_messages (
    id bigint generated by default as identity primary key,
    wave_id bigint not null,
    -- El dia del chat: los conductores con turno en la ola ese dia. Los mensajes de otros dias ya no se piden
    work_date date not null,
    sender_id bigint not null,
    body varchar(1000),
    -- Nombre del fichero que guardo el servidor (nunca una ruta); las fotos viven en disco, como las de los partes
    photo_file varchar(255),
    sent_at timestamp(6) not null,
    -- Un chat no tiene sentido sin su ola. Al borrar la ola se borran sus mensajes (las fotos se quedan en disco)
    constraint fk_wave_messages_wave foreign key (wave_id) references waves (id) on delete cascade,
    constraint fk_wave_messages_sender foreign key (sender_id) references users (id),
    -- Un mensaje nunca esta vacio: texto, foto o ambos
    constraint ck_wave_messages_content check (body is not null or photo_file is not null)
);

-- El chat se lee siempre igual: los mensajes de una ola un dia, por orden de llegada (id), y a partir de uno dado
create index idx_wave_messages_chat on wave_messages (wave_id, work_date, id);
create index idx_wave_messages_sender on wave_messages (sender_id);
