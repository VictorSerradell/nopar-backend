-- V9: llamadas a una ola ("Ola 1, subid") y su confirmacion por los conductores, y el rol de encargado.

-- Encargado (MANAGER): puede llamar a las olas igual que un administrador, pero nada mas.
alter table users drop constraint if exists users_role_check;
alter table users add constraint users_role_check check (role in ('DRIVER', 'MANAGER', 'ADMIN'));

create table wave_calls (
    id bigint generated by default as identity primary key,
    wave_id bigint not null,
    -- El dia al que se refiere la llamada: los conductores con turno en esa ola ese dia
    work_date date not null,
    message varchar(140) not null,
    called_by bigint not null,
    called_at timestamp(6) not null,
    -- Una llamada no tiene sentido sin su ola: al borrar la ola se borran sus llamadas (y, en cascada, sus destinatarios)
    constraint fk_wave_calls_wave foreign key (wave_id) references waves (id) on delete cascade,
    constraint fk_wave_calls_called_by foreign key (called_by) references users (id)
);

-- Las llamadas de un dia se piden con frecuencia (la pantalla del encargado y "mis llamadas de hoy")
create index idx_wave_calls_work_date on wave_calls (work_date);
create index idx_wave_calls_wave on wave_calls (wave_id);
create index idx_wave_calls_called_by on wave_calls (called_by);

-- A quien se llamo: una fila por conductor, con la furgoneta que tenia en el momento de la llamada. La hora de
-- confirmacion ("Enterado") esta vacia hasta que el conductor la pulsa
create table wave_call_recipients (
    id bigint generated by default as identity primary key,
    wave_call_id bigint not null,
    driver_id bigint not null,
    vehicle_license_plate varchar(20) not null,
    acknowledged_at timestamp(6),
    constraint fk_wave_call_recipients_call foreign key (wave_call_id) references wave_calls (id) on delete cascade,
    constraint fk_wave_call_recipients_driver foreign key (driver_id) references users (id) on delete cascade,
    -- Un conductor aparece una sola vez por llamada. La restriccion tambien sirve de indice por llamada
    constraint uk_wave_call_recipients_call_driver unique (wave_call_id, driver_id)
);

-- "Mis llamadas de hoy" busca por conductor
create index idx_wave_call_recipients_driver on wave_call_recipients (driver_id);
