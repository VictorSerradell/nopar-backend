-- V6: tablon de avisos. Los avisos de la empresa y quien los ha leido.

create table announcements (
    id bigint generated by default as identity primary key,
    title varchar(120) not null,
    body varchar(4000) not null,
    pinned boolean not null default false,
    created_by bigint not null,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    constraint fk_announcements_created_by foreign key (created_by) references users (id)
);

-- El tablon se lee siempre en el mismo orden: primero los fijados y luego los mas recientes
create index idx_announcements_board on announcements (pinned desc, created_at desc, id desc);

create table announcement_reads (
    id bigint generated by default as identity primary key,
    announcement_id bigint not null,
    user_id bigint not null,
    read_at timestamp(6) not null,
    -- Un usuario lee un aviso una sola vez. Esta restriccion tambien sirve de indice para saber quien ha leido
    -- un aviso y cuales de los avisos de una pagina ha leido un usuario (announcement_id va primero)
    constraint uk_announcement_reads_announcement_user unique (announcement_id, user_id),
    -- Al borrar un aviso se borran sus lecturas
    constraint fk_announcement_reads_announcement foreign key (announcement_id) references announcements (id) on delete cascade,
    constraint fk_announcement_reads_user foreign key (user_id) references users (id)
);

-- PostgreSQL no indexa por si solo las claves foraneas
create index idx_announcement_reads_user on announcement_reads (user_id);
