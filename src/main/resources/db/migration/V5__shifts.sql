-- V5: cuadrantes. Las olas (franjas de salida) y la asignacion diaria de conductor y furgoneta a cada ola.

create table waves (
    id bigint generated by default as identity primary key,
    name varchar(50) not null,
    start_time time not null,
    constraint uk_waves_name unique (name)
);

create table shift_assignments (
    id bigint generated by default as identity primary key,
    work_date date not null,
    wave_id bigint not null,
    driver_id bigint not null,
    vehicle_id bigint not null,
    created_by bigint not null,
    created_at timestamp(6) not null,
    constraint fk_shift_assignments_wave foreign key (wave_id) references waves (id),
    constraint fk_shift_assignments_driver foreign key (driver_id) references users (id),
    constraint fk_shift_assignments_vehicle foreign key (vehicle_id) references vehicles (id),
    constraint fk_shift_assignments_created_by foreign key (created_by) references users (id),
    -- Un conductor y una furgoneta solo pueden estar en un turno al dia. Las restricciones unicas tambien sirven
    -- de indice para pedir el cuadrante de un rango de fechas (work_date va primero)
    constraint uk_shift_assignments_driver_day unique (work_date, driver_id),
    constraint uk_shift_assignments_vehicle_day unique (work_date, vehicle_id)
);

-- PostgreSQL no indexa por si solo las claves foraneas: "mis turnos" filtra por conductor y fecha, y borrar una
-- ola o una furgoneta comprueba si tienen turnos
create index idx_shift_assignments_driver_date on shift_assignments (driver_id, work_date);
create index idx_shift_assignments_vehicle on shift_assignments (vehicle_id);
create index idx_shift_assignments_wave on shift_assignments (wave_id);
