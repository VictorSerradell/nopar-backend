-- V1: esquema base de Nopar, tal y como lo tenia la aplicacion antes de pasar a Flyway.
--
-- Solo se ejecuta en una base de datos vacia. Una base ya existente (creada antes con
-- spring.jpa.hibernate.ddl-auto=update) se toma como la version 1 gracias a baseline-on-migrate
-- y esta migracion no se aplica sobre ella.
--
-- Los nombres de columna siguen la convencion de Spring Boot: camelCase -> snake_case.
-- Ojo: beaconV16Present da "beacon_v16_present" (la convencion tambien separa antes de los digitos).

create table users (
    id bigint generated by default as identity primary key,
    username varchar(255) not null,
    password varchar(255) not null,
    role varchar(255) not null,
    constraint uk_users_username unique (username),
    constraint users_role_check check (role in ('DRIVER', 'ADMIN'))
);

create table vehicles (
    id bigint generated by default as identity primary key,
    license_plate varchar(20) not null,
    model varchar(255) not null,
    has_beacon boolean not null,
    current_kilometers integer not null,
    status varchar(255) not null,
    constraint uk_vehicles_license_plate unique (license_plate),
    constraint vehicles_status_check check (status in ('AVAILABLE', 'IN_USE', 'MAINTENANCE', 'DAMAGED'))
);

create table refresh_tokens (
    id bigint generated by default as identity primary key,
    -- SHA-256 del token en hexadecimal, nunca el token en claro
    token varchar(255) not null,
    expiry_date timestamp(6) with time zone not null,
    user_id bigint,
    constraint uk_refresh_tokens_token unique (token),
    constraint fk_refresh_tokens_user foreign key (user_id) references users (id)
);

create table vehicle_inspections (
    id bigint generated by default as identity primary key,
    vehicle_id bigint not null,
    user_id bigint not null,
    inspection_date timestamp(6) not null,
    kilometers integer not null,
    tires_ok boolean,
    lights_ok boolean,
    beacon_v16_present boolean,
    odometer_photo_path varchar(255),
    beacon_photo_path varchar(255),
    exterior_photos_path varchar(255),
    damages_reported text,
    accepted_exclusive_use boolean,
    accepted_liability boolean,
    accepted_cleanliness boolean,
    status varchar(255) not null,
    constraint fk_vehicle_inspections_vehicle foreign key (vehicle_id) references vehicles (id),
    constraint fk_vehicle_inspections_driver foreign key (user_id) references users (id),
    constraint vehicle_inspections_status_check check (status in ('SUBMITTED', 'APPROVED', 'REJECTED'))
);
