-- V4: devolucion del vehiculo al acabar el turno (quien, cuando, con cuantos kilometros y si reporto danos).

create table vehicle_returns (
    id bigint generated by default as identity primary key,
    vehicle_id bigint not null,
    returned_by bigint not null,
    returned_at timestamp(6) not null,
    kilometers integer not null,
    damages_reported text,
    constraint fk_vehicle_returns_vehicle foreign key (vehicle_id) references vehicles (id),
    constraint fk_vehicle_returns_user foreign key (returned_by) references users (id)
);

create index idx_vehicle_returns_vehicle_date on vehicle_returns (vehicle_id, returned_at desc, id desc);
