-- V12: hasta que mensaje ha leido cada usuario el chat de cada ola. Con eso se cuentan los mensajes sin leer (los de
-- hoy, de otros, posteriores a ese). Los ids de mensaje solo crecen, asi que basta guardar el ultimo leido: no hace
-- falta separar por dia (los mensajes de hoy siempre tienen un id mayor que los de ayer).

create table wave_chat_reads (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    wave_id bigint not null,
    -- El mensaje mas reciente que el usuario ha visto en ese chat. Solo avanza, nunca retrocede
    last_read_id bigint not null,
    updated_at timestamp(6) not null,
    -- Es solo un marcador: si desaparece el usuario o la ola, desaparece con ellos
    constraint fk_wave_chat_reads_user foreign key (user_id) references users (id) on delete cascade,
    constraint fk_wave_chat_reads_wave foreign key (wave_id) references waves (id) on delete cascade,
    -- Una fila por usuario y ola: la insercion nativa con "on conflict" se apoya en esta restriccion
    constraint uq_wave_chat_reads_user_wave unique (user_id, wave_id)
);

-- Contar los no leidos filtra por dia en todas las olas a la vez: el indice de V11 empieza por la ola y no sirve
create index idx_wave_messages_date on wave_messages (work_date, wave_id, id);
